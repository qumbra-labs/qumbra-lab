//! Measured-report driver for qlab-cbserver.
//!
//! Prints a Markdown report to stdout: wire bytes/note (1-of-1 & 2-of-1) with
//! §2 framing overhead vs the spec's ~600 B; end-to-end scan throughput
//! (notes/s over localhost, single client); and `/v1/tree/frontier` round-trip
//! correctness against the devnet tree. Run twice → `docs/cbserver-run{1,2}.md`.
//!
//! Usage: `cargo run --release -p qlab-cbserver --bin cbreport -- [label]`

use std::sync::Arc;
use std::time::Instant;

use qlab_cbserver::client::{light_client_scan, DecoyPolicy, ScanConfig};
use qlab_cbserver::codec::{group_len, CompactGroup};
use qlab_cbserver::data::{Devnet, GenParams};
use qlab_cbserver::server::serve;
use qlab_cbserver::tree::Frontier;
use qlab_note::kem::{generate_keypair, CT_LEN};
use qlab_note::scan::{encrypt_to_recipient, ScanMode};
use qlab_note::wire::{bytes_per_note_amortized, CompactEntry};
use rand::rngs::StdRng;
use rand::SeedableRng;

const ENTRY_LEN: usize = CompactEntry::LEN_EMPTY_CLUE; // 41

/// Build a single-recipient compact group with `k` real encrypted outputs.
fn one_recipient_group(k: usize, rng: &mut StdRng) -> CompactGroup {
    let kp = generate_keypair(rng);
    let notes: Vec<qlab_note::note::Note> = (0..k)
        .map(|i| qlab_note::note::Note {
            value: 42 + i as u64,
            rkm: [1, 2, 3, 4],
            rho: [5, 6, 7, 8],
            rseed: [9, 10, 11, 12],
        })
        .collect();
    let enc = encrypt_to_recipient(&kp.ek, &notes, rng);
    CompactGroup { tx_index: 0, recipients: vec![enc.bundle] }
}

fn main() {
    let label = std::env::args().nth(1).unwrap_or_else(|| "run".to_string());
    let mut rng = StdRng::seed_from_u64(0xB10C);

    println!("# qlab-cbserver measured run — {label}\n");
    println!("Compact-block reference server (wallet-interop-spec §2) over the ratified");
    println!("note-discovery §2 wire. Generated by `cbreport`; localhost only.\n");
    println!("| field | value |");
    println!("|---|---|");
    println!("| git rev | `{}` |", env_or("GIT_REV", "(fill: git rev-parse --short HEAD)"));
    println!("| hardware | {} |", env_or("RIG", "(fill: e.g. Apple M5 Max / 36 GiB)"));
    println!("| os | {} |", env_or("OSVER", "(fill: e.g. macOS 15.x / Darwin 25.5.0)"));
    println!("| power | {} |", env_or("POWER", "(fill: AC / battery, thermal)"));
    println!("| server crate | `tiny_http` =0.12.0 |");
    println!("| ML-KEM ct | {CT_LEN} B | ");
    println!();

    // ---- 1. Wire bytes/note with framing overhead ----------------------------
    println!("## 1. Wire bytes/note (framing overhead included)\n");
    println!("`raw` = note-discovery amortized accounting (cm 32 + tag 8 + clue 1 + ⌈1088/k⌉).");
    println!("`framed` = the full §2 compact group serialized by this reference (adds");
    println!("tx_index varint + n_recipients + n_outputs per group).\n");
    println!("| amortization | raw B/note | framed B/note | framing overhead | doc target |");
    println!("|---|---|---|---|---|");
    for k in [1usize, 2] {
        let g = one_recipient_group(k, &mut rng);
        let framed_group = group_len(&g);
        let raw_group = CT_LEN + k * ENTRY_LEN;
        let overhead_group = framed_group - raw_group;
        let raw_per_note = bytes_per_note_amortized(k);
        let framed_per_note = framed_group as f64 / k as f64;
        let target = if k == 1 { "~1.1 KB" } else { "~600 B (585 measured)" };
        println!(
            "| {k}-of-1 | {raw_per_note} | {framed_per_note:.1} | {overhead_group} B/group ({:.1} B/note) | {target} |",
            overhead_group as f64 / k as f64
        );
    }
    println!();
    println!("Framing overhead is a fixed **{} B per per-tx group** (tx_index 1 + n_recipients 1 + n_outputs 1)", 3);
    println!("for the single-recipient case — independent of the 1,088-B ct and the entry count.");
    println!("The response wrapper adds version 1 + n_blocks(varint) + per-block height(varint) + n_groups(varint).\n");

    // ---- Whole-range response accounting -------------------------------------
    let devnet = Arc::new(Devnet::generate(GenParams::default()));
    let range = devnet.compact_range(1, devnet.tip_height());
    let resp = qlab_cbserver::codec::encode_compact_response(&range);
    let total_entries: usize = range
        .iter()
        .flat_map(|b| &b.groups)
        .flat_map(|g| &g.recipients)
        .map(|r| r.entries.len())
        .sum();
    println!("Whole devnet range (heights 1..={}): {} compact bytes over {} notes = {:.1} B/note framed.\n",
        devnet.tip_height(), resp.len(), total_entries, resp.len() as f64 / total_entries as f64);

    // ---- 2. Scan throughput over localhost -----------------------------------
    println!("## 2. End-to-end scan throughput (single client, localhost)\n");
    let handle = serve(Arc::clone(&devnet));
    let base = handle.base_url();
    // Warm the connection path once (untimed).
    let mut warm_rng = StdRng::seed_from_u64(1);
    let _ = light_client_scan(&base, &devnet.our.dk, 1, devnet.tip_height(),
        ScanConfig { mode: ScanMode::FullFo, decoy: DecoyPolicy::Off }, &mut warm_rng).unwrap();

    let mut scan_rng = StdRng::seed_from_u64(2);
    let t0 = Instant::now();
    let out = light_client_scan(&base, &devnet.our.dk, 1, devnet.tip_height(),
        ScanConfig { mode: ScanMode::FullFo, decoy: DecoyPolicy::PerMatch { max: 1 } }, &mut scan_rng).unwrap();
    let elapsed = t0.elapsed();

    // Entries scanned = every compact entry decapsulated/tag-checked.
    let entries_scanned: usize = range
        .iter()
        .flat_map(|b| &b.groups)
        .flat_map(|g| &g.recipients)
        .map(|r| r.entries.len())
        .sum();
    let secs = elapsed.as_secs_f64();
    println!("| metric | value |");
    println!("|---|---|");
    println!("| range | heights 1..={} |", devnet.tip_height());
    println!("| entries scanned | {entries_scanned} |");
    println!("| notes found | {} (expected {}) |", out.stats.notes_found, devnet.expected_matches);
    println!("| matched /full fetches | {} |", out.stats.matched_fetches);
    println!("| decoy /full fetches | {} |", out.stats.decoy_fetches);
    println!("| compact response bytes | {} |", out.stats.compact_bytes);
    println!("| wall time | {:.3} ms |", secs * 1e3);
    println!("| scan throughput | {:.0} entries/s |", entries_scanned as f64 / secs);
    println!("| note-detection rate | {:.0} notes/s |", out.stats.notes_found as f64 / secs);
    println!("| server requests served | {} |", handle.requests_served());
    println!();
    println!("Wall time is **connection-bound**: the reference client uses `Connection: close`");
    println!("(one TCP round-trip per fetch) and the decoy hook is ON (≥1 decoy per matched");
    println!("fetch), so ~{} localhost connections dominate — not the ML-KEM decap (54k/s,",
        1 + out.stats.matched_fetches + out.stats.decoy_fetches);
    println!("PR #28). It is an honest end-to-end localhost number for this reference, not a");
    println!("tuned-transport ceiling (HTTP keep-alive / batched /full would raise it).\n");
    assert_eq!(out.stats.notes_found, devnet.expected_matches, "scan must find all planted notes");

    // ---- 3. Frontier round-trip against the devnet tree ----------------------
    println!("## 3. /v1/tree/frontier round-trip correctness\n");
    println!("| at height | leaves | reconstructed root == tree.root_at | frontier bytes |");
    println!("|---|---|---|---|");
    let mut all_ok = true;
    for h in [0u64, 1, 2, 4, devnet.tip_height()] {
        let bytes = qlab_cbserver::server::route(&devnet, &format!("/v1/tree/frontier?at={h}")).unwrap();
        let f = Frontier::from_bytes(&bytes).unwrap();
        let count = devnet.leaves_at(h);
        let ok = f.root() == devnet.tree.root_at(count);
        all_ok &= ok;
        println!("| {h} | {count} | {} | {} |", if ok { "✅ PASS" } else { "❌ FAIL" }, bytes.len());
    }
    println!();
    assert!(all_ok, "every served frontier must reconstruct the tree root");

    handle.shutdown();
    println!("All assertions passed: bytes/note framed, throughput measured, frontier round-trips exact.");
}

fn env_or(key: &str, default: &str) -> String {
    std::env::var(key).unwrap_or_else(|_| default.to_string())
}
